export type GuideKind = "club" | "agency" | "admin";

export const clubGuides: Record<ClubLocale, HelpGuide> = { de: clubGuideDe, en: clubGuideEn, fr: clubGuideFr, es: clubGuideEs };

/** Agency guide exists in German and English; French and Spanish agencies get English. */
export function getGuide(kind: GuideKind, locale: ClubLocale): HelpGuide {
  if (kind === "admin") return adminGuideDe;
  if (kind === "agency") return locale === "de" ? agencyGuideDe : agencyGuideEn;
  return clubGuides[locale];
}

